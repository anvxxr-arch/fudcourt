-- 2. token — one contract deployment on one chain; address stored verbatim.
CREATE TABLE IF NOT EXISTS data.token (
  token_id     text PRIMARY KEY,
  chain_id     text NOT NULL,
  address      text NOT NULL,
  address_kind text,
