-- 10. provider_symbol — the (provider, symbol) -> canonical id resolution
-- table. The CHECK mirrors pg-schema.sql's canonical_reference_kind_prefix:
-- kind must agree with the id's own namespace prefix, enforced at the
-- database so a wrong-namespace mapping is refused at write time. Named and
-- re-guarded in the DO block for the same re-apply reason as above.
CREATE TABLE IF NOT EXISTS data.provider_symbol (
  provider        text NOT NULL,
  provider_symbol text NOT NULL,
  kind            text NOT NULL,
  canonical_id    text NOT NULL,
  verified        boolean NOT NULL DEFAULT false,
  last_seen_at    timestamptz,
  PRIMARY KEY (provider, provider_symbol, kind),
  CONSTRAINT provider_symbol_canonical_id_kind CHECK (canonical_id LIKE kind || ':%')
);
DO $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_constraint
                  WHERE conrelid = 'data.provider_symbol'::regclass
                    AND conname  = 'provider_symbol_canonical_id_kind') THEN
    ALTER TABLE data.provider_symbol
      ADD CONSTRAINT provider_symbol_canonical_id_kind
      CHECK (canonical_id LIKE kind || ':%');
  END IF;
END
$$;
CREATE INDEX IF NOT EXISTS provider_symbol_canonical_id_idx ON data.provider_symbol (canonical_id);

