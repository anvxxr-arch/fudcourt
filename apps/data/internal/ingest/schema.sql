-- § Job model + observability.

-- 12. job — the persisted registry row for one dataset job. The UNIQUE tuple
-- is the JobRef identity; cursor/last_*/status/retry_count are runtime state
-- the engine owns (EnsureJobs upserts schedule/priority/enabled and leaves
-- this state alone).
CREATE TABLE IF NOT EXISTS data.job (
  id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  provider         text NOT NULL,
  dataset          text NOT NULL,
  subject          text NOT NULL DEFAULT '',
  mode             text NOT NULL DEFAULT 'poll',
  schedule_seconds int NOT NULL,
  priority         int NOT NULL DEFAULT 5,
  enabled          boolean NOT NULL DEFAULT true,
  cursor           jsonb,
  last_success     timestamptz,
  last_attempt     timestamptz,
  status           text NOT NULL DEFAULT 'idle',
  retry_count      int NOT NULL DEFAULT 0,
  created_at       timestamptz NOT NULL DEFAULT now(),
  updated_at       timestamptz NOT NULL DEFAULT now()
);
DO $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'job_provider_dataset_subject_mode_key') THEN
    ALTER TABLE data.job
      ADD CONSTRAINT job_provider_dataset_subject_mode_key
      UNIQUE (provider, dataset, subject, mode);
  END IF;
END
$$;
-- Scheduler's hot query: candidates are enabled jobs (DueJobs filters
-- last_attempt + schedule_seconds <= now, but enabled is the cheap pre-filter
-- the partial index serves).
CREATE INDEX IF NOT EXISTS job_enabled_status_idx ON data.job (status) WHERE enabled;

