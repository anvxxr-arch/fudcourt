import fs from 'node:fs';
const txt = fs.readFileSync('/home/dwizzy/wallet_combined_2months_enriched.csv','utf8').replace(/\r/g,'');
const lines = txt.split('\n').filter(l => l.trim());
const hdr = lines[0].split(',');
const recs = lines.slice(1).map(l => { const p = l.split(','); const o = {}; hdr.forEach((h,i)=>o[h]=p[i]); return o; });
const real = recs.filter(r => /Binance-Peg/.test(r.asset||''));
console.log('=== REAL Binance-Peg transfers:', real.length, '===');
for (const r of real) console.log([r.chain,r.time,r.type,(r.asset||'').slice(0,28),r.amount,r.usd_value,r.direction,r.hash].join(' | '));
console.log('\n=== Fake/dust lookalikes (zero usd value) ===');
const fake = recs.filter(r => /U5D|UႽD|U឵S/.test(r.asset||''));
for (const r of fake) console.log([r.chain,r.time,r.type,(r.asset||'').slice(0,30),r.amount,r.usd_value,r.direction,r.hash].join(' | '));
console.log('\nfake count', fake.length);
console.log('\n=== All BSC non-dust rows ===');
for (const r of recs.filter(r=>r.chain==='BSC' && Number(r.usd_value||0) > 0)) console.log([r.chain,r.time,r.type,(r.asset||'').slice(0,30),r.amount,r.usd_value,r.direction,r.hash].join(' | '));